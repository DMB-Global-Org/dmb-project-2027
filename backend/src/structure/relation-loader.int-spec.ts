import {
  createOrg,
  createPartner,
  createSuperAdmin,
} from '../../test/support/fixtures.js';
import { createTestDb, type TestDb } from '../../test/support/test-db.js';
import type { AuthContext } from '../auth/auth.types.js';
import { RelationLoader } from './relation-loader.js';

describe('RelationLoader (integration)', () => {
  let testDb: TestDb;
  let loader: RelationLoader;
  let org: string;
  // root -> a -> b ; root -> c
  let root: string, a: string, b: string, c: string;

  const asActor = (
    accountId: string,
    orgSchema: string | null,
  ): AuthContext => ({
    accountId,
    email: 'x@example.com',
    locale: 'pl',
    orgSchema,
    actor: { accountId, role: 'GENERAL', state: 'ACTIVE' },
  });

  beforeAll(async () => {
    testDb = createTestDb();
    loader = new RelationLoader(testDb.db);
    org = await createOrg(testDb);
    root = (await createPartner(testDb, org, { role: 'PLATINUM' })).accountId;
    a = (await createPartner(testDb, org, { recommenderId: root })).accountId;
    b = (await createPartner(testDb, org, { recommenderId: a })).accountId;
    c = (await createPartner(testDb, org, { recommenderId: root })).accountId;
  });

  afterAll(async () => {
    await testDb.close();
  });

  describe('isSelfOrAncestor', () => {
    it('is true for the account itself', async () => {
      expect(await loader.isSelfOrAncestor(org, a, a)).toBe(true);
    });

    it('is true for any account above, however far', async () => {
      expect(await loader.isSelfOrAncestor(org, a, b)).toBe(true);
      expect(await loader.isSelfOrAncestor(org, root, b)).toBe(true);
    });

    it('is false for a descendant, a sibling branch or a stranger', async () => {
      expect(await loader.isSelfOrAncestor(org, b, a)).toBe(false);
      expect(await loader.isSelfOrAncestor(org, c, b)).toBe(false);
      expect(
        await loader.isSelfOrAncestor(
          org,
          '00000000-0000-4000-8000-000000000000',
          b,
        ),
      ).toBe(false);
    });

    it('refuses a schema name that is not generated by the server', async () => {
      await expect(
        loader.isSelfOrAncestor('app; drop schema app', a, b),
      ).rejects.toThrow('Invalid organization schema name');
    });
  });

  describe('inviteRecommenderFacts', () => {
    it('says the actor is the sponsor or above them, in the same organization', async () => {
      const self = await loader.inviteRecommenderFacts(asActor(a, org), a);
      const above = await loader.inviteRecommenderFacts(asActor(a, org), b);

      expect(self?.facts.actorIsAncestorOrSelf).toBe(true);
      expect(above?.facts.actorIsAncestorOrSelf).toBe(true);
      expect(above?.orgSchema).toBe(org);
    });

    it('says no for somebody above, beside or in another organization', async () => {
      const otherOrg = await createOrg(testDb);
      const stranger = (await createPartner(testDb, otherOrg)).accountId;

      for (const [actor, target] of [
        [asActor(b, org), a],
        [asActor(c, org), b],
        [asActor(stranger, otherOrg), b],
      ] as const) {
        const result = await loader.inviteRecommenderFacts(actor, target);
        expect(result?.facts.actorIsAncestorOrSelf).toBe(false);
      }
    });

    it('reports the state of the sponsor', async () => {
      const inactive = (
        await createPartner(testDb, org, {
          recommenderId: root,
          state: 'DEACTIVATED',
        })
      ).accountId;

      const result = await loader.inviteRecommenderFacts(
        asActor(root, org),
        inactive,
      );
      expect(result?.facts.state).toBe('DEACTIVATED');
    });

    it('is null for unknown accounts and for SuperAdministrators', async () => {
      const superAdmin = await createSuperAdmin(testDb);

      expect(
        await loader.inviteRecommenderFacts(
          asActor(a, org),
          '00000000-0000-4000-8000-000000000000',
        ),
      ).toBeNull();
      expect(
        await loader.inviteRecommenderFacts(
          asActor(a, org),
          superAdmin.accountId,
        ),
      ).toBeNull();
    });
  });
});
