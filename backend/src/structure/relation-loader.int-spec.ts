import {
  createOrg,
  createOrgWithRoot,
  createPartner,
  createSuperAdmin,
} from '../../test/support/fixtures.js';
import { createTestDb, type TestDb } from '../../test/support/test-db.js';
import type { AuthContext } from '../auth/auth.types.js';
import { eq } from 'drizzle-orm';
import { orgTables } from '../db/org/org-tables.js';
import { orgSchemas } from '../db/schema/index.js';
import { RelationLoader } from './relation-loader.js';

describe('RelationLoader (integration)', () => {
  let testDb: TestDb;
  let loader: RelationLoader;
  let org: string;
  // root -> a -> b ; root -> c
  let root: string, a: string, b: string, c: string;

  const asActor = (
    accountId: string,
    orgSchema: string | null,
  ): AuthContext => ({
    accountId,
    email: 'x@example.com',
    locale: 'pl',
    orgSchema,
    actor: { accountId, role: 'GENERAL', state: 'ACTIVE' },
  });

  beforeAll(async () => {
    testDb = createTestDb();
    loader = new RelationLoader(testDb.db);
    org = await createOrg(testDb);
    root = (await createPartner(testDb, org, { role: 'PLATINUM' })).accountId;
    a = (await createPartner(testDb, org, { recommenderId: root })).accountId;
    b = (await createPartner(testDb, org, { recommenderId: a })).accountId;
    c = (await createPartner(testDb, org, { recommenderId: root })).accountId;
  });

  afterAll(async () => {
    await testDb.close();
  });

  describe('isSelfOrAncestor', () => {
    it('is true for the account itself', async () => {
      expect(await loader.isSelfOrAncestor(org, a, a)).toBe(true);
    });

    it('is true for any account above, however far', async () => {
      expect(await loader.isSelfOrAncestor(org, a, b)).toBe(true);
      expect(await loader.isSelfOrAncestor(org, root, b)).toBe(true);
    });

    it('is false for a descendant, a sibling branch or a stranger', async () => {
      expect(await loader.isSelfOrAncestor(org, b, a)).toBe(false);
      expect(await loader.isSelfOrAncestor(org, c, b)).toBe(false);
      expect(
        await loader.isSelfOrAncestor(
          org,
          '00000000-0000-4000-8000-000000000000',
          b,
        ),
      ).toBe(false);
    });

    it('refuses a schema name that is not generated by the server', async () => {
      await expect(
        loader.isSelfOrAncestor('app; drop schema app', a, b),
      ).rejects.toThrow('Invalid organization schema name');
    });
  });

  describe('inviteRecommenderFacts', () => {
    it('says the actor is the sponsor or above them, in the same organization', async () => {
      const self = await loader.inviteRecommenderFacts(asActor(a, org), a);
      const above = await loader.inviteRecommenderFacts(asActor(a, org), b);

      expect(self?.facts.actorIsAncestorOrSelf).toBe(true);
      expect(above?.facts.actorIsAncestorOrSelf).toBe(true);
      expect(above?.orgSchema).toBe(org);
    });

    it('says no for somebody above, beside or in another organization', async () => {
      const otherOrg = await createOrg(testDb);
      const stranger = (await createPartner(testDb, otherOrg)).accountId;

      for (const [actor, target] of [
        [asActor(b, org), a],
        [asActor(c, org), b],
        [asActor(stranger, otherOrg), b],
      ] as const) {
        const result = await loader.inviteRecommenderFacts(actor, target);
        expect(result?.facts.actorIsAncestorOrSelf).toBe(false);
      }
    });

    it('reports the state of the sponsor', async () => {
      const inactive = (
        await createPartner(testDb, org, {
          recommenderId: root,
          state: 'DEACTIVATED',
        })
      ).accountId;

      const result = await loader.inviteRecommenderFacts(
        asActor(root, org),
        inactive,
      );
      expect(result?.facts.state).toBe('DEACTIVATED');
    });

    it('is null for unknown accounts and for SuperAdministrators', async () => {
      const superAdmin = await createSuperAdmin(testDb);

      expect(
        await loader.inviteRecommenderFacts(
          asActor(a, org),
          '00000000-0000-4000-8000-000000000000',
        ),
      ).toBeNull();
      expect(
        await loader.inviteRecommenderFacts(
          asActor(a, org),
          superAdmin.accountId,
        ),
      ).toBeNull();
    });
  });

  describe('targetFacts', () => {
    let tOrg: string;
    let tRoot: string, tA: string, tB: string, tC: string;

    beforeAll(async () => {
      tOrg = await createOrg(testDb);
      tRoot = (await createPartner(testDb, tOrg, { role: 'PLATINUM' }))
        .accountId;
      tA = (await createPartner(testDb, tOrg, { recommenderId: tRoot }))
        .accountId;
      tB = (await createPartner(testDb, tOrg, { recommenderId: tA })).accountId;
      tC = (
        await createPartner(testDb, tOrg, {
          recommenderId: tRoot,
          state: 'PENDING_ACTIVATION',
        })
      ).accountId;
      await testDb.db
        .update(orgSchemas)
        .set({ rootAccountId: tRoot })
        .where(eq(orgSchemas.name, tOrg));
    });

    it('describes a member of the actor downline', async () => {
      const result = await loader.targetFacts(asActor(tA, tOrg), tB);

      expect(result?.orgSchema).toBe(tOrg);
      expect(result?.facts).toEqual({
        role: 'GENERAL',
        state: 'ACTIVE',
        removed: false,
        isSelf: false,
        sameOrg: true,
        actorIsAncestor: true,
        isOrgRoot: false,
        actorIsAboveOrg: false,
      });
    });

    it('marks the actor themselves and the root of the organization', async () => {
      const self = await loader.targetFacts(asActor(tA, tOrg), tA);
      expect(self?.facts.isSelf).toBe(true);
      expect(self?.facts.actorIsAncestor).toBe(false);

      const root = await loader.targetFacts(asActor(tA, tOrg), tRoot);
      expect(root?.facts.isOrgRoot).toBe(true);
      expect(root?.facts.actorIsAncestor).toBe(false);
      expect(root?.facts.sameOrg).toBe(true);
    });

    it('says nobody is above a branch beside or below the actor', async () => {
      const beside = await loader.targetFacts(asActor(tC, tOrg), tB);
      const below = await loader.targetFacts(asActor(tB, tOrg), tA);
      expect(beside?.facts.actorIsAncestor).toBe(false);
      expect(below?.facts.actorIsAncestor).toBe(false);
    });

    it('does not claim ancestry for another organization or a SuperAdministrator', async () => {
      const otherOrg = await createOrg(testDb);
      const stranger = (await createPartner(testDb, otherOrg)).accountId;
      const superAdmin = await createSuperAdmin(testDb);

      const foreign = await loader.targetFacts(asActor(stranger, otherOrg), tB);
      expect(foreign?.facts.sameOrg).toBe(false);
      expect(foreign?.facts.actorIsAncestor).toBe(false);

      const fromSuper = await loader.targetFacts(
        asActor(superAdmin.accountId, null),
        tB,
      );
      expect(fromSuper?.facts.sameOrg).toBe(false);
    });

    it('is null for unknown accounts and for SuperAdministrators', async () => {
      const superAdmin = await createSuperAdmin(testDb);
      const actor = asActor(tA, tOrg);

      expect(
        await loader.targetFacts(actor, '00000000-0000-4000-8000-000000000000'),
      ).toBeNull();
      expect(await loader.targetFacts(actor, superAdmin.accountId)).toBeNull();
    });
  });

  describe('downline', () => {
    it('lists the root and everybody below, parents before children', async () => {
      const dOrg = await createOrg(testDb);
      const r = (await createPartner(testDb, dOrg, { role: 'PLATINUM' }))
        .accountId;
      const x = (await createPartner(testDb, dOrg, { recommenderId: r }))
        .accountId;
      const x1 = (await createPartner(testDb, dOrg, { recommenderId: x }))
        .accountId;
      const y = (await createPartner(testDb, dOrg, { recommenderId: r }))
        .accountId;
      const x2 = (await createPartner(testDb, dOrg, { recommenderId: x }))
        .accountId;

      expect(await loader.downline(dOrg, r)).toEqual([
        { accountId: r, depth: 0 },
        { accountId: x, depth: 1 },
        { accountId: x1, depth: 2 },
        { accountId: x2, depth: 2 },
        { accountId: y, depth: 1 },
      ]);
      expect(await loader.downline(dOrg, x)).toEqual([
        { accountId: x, depth: 0 },
        { accountId: x1, depth: 1 },
        { accountId: x2, depth: 1 },
      ]);
    });

    it('does not loop over a corrupted, cyclic chain', async () => {
      const cOrg = await createOrg(testDb);
      const p = (await createPartner(testDb, cOrg)).accountId;
      const q = (await createPartner(testDb, cOrg, { recommenderId: p }))
        .accountId;
      const { partners } = orgTables(cOrg);
      await testDb.db
        .update(partners)
        .set({ recommenderId: q })
        .where(eq(partners.accountId, p));

      const rows = await loader.downline(cOrg, p);
      expect(rows.map((row) => row.accountId)).toEqual([p, q]);
    });

    it('refuses a schema name that is not generated by the server', async () => {
      await expect(loader.downline('app; drop schema app', a)).rejects.toThrow(
        'Invalid organization schema name',
      );
    });
  });

  describe('actorIsAboveOrg', () => {
    let org0: string, org1: string, org2: string;
    let root0: string, m: string, x1: string, y: string, x2: string;

    /** The marker of an account that now heads `schema` (decision 87). */
    const detach = async (
      schema: string,
      accountId: string,
      source: string,
      by: string,
    ) => {
      await testDb.db.insert(orgTables(schema).partners).values({
        accountId,
        role: 'PLATINUM',
        state: 'ACTIVE',
      });
      await testDb.db
        .update(orgSchemas)
        .set({
          rootAccountId: accountId,
          sourceSchema: source,
          promotedBy: by,
          promotedAt: new Date(),
        })
        .where(eq(orgSchemas.name, schema));
    };

    beforeAll(async () => {
      // org0: root0 -> m -> x1 (marker; x1 heads org1)
      // org1: x1 -> y -> x2 (marker; x2 heads org2)
      const first = await createOrgWithRoot(testDb);
      org0 = first.org;
      root0 = first.root.accountId;
      m = (await createPartner(testDb, org0, { recommenderId: root0 }))
        .accountId;
      x1 = (await createPartner(testDb, org0, { recommenderId: m })).accountId;
      org1 = await createOrg(testDb);
      await detach(org1, x1, org0, root0);
      y = (await createPartner(testDb, org1, { recommenderId: x1 })).accountId;
      x2 = (await createPartner(testDb, org1, { recommenderId: y })).accountId;
      org2 = await createOrg(testDb);
      await detach(org2, x2, org1, x1);
    });

    it('is true for somebody above the marker, however high', async () => {
      expect(await loader.actorIsAboveOrg(asActor(m, org0), org1)).toBe(true);
      expect(await loader.actorIsAboveOrg(asActor(root0, org0), org1)).toBe(
        true,
      );
    });

    it('follows the registry up: a Platinum of a Platinum is above', async () => {
      expect(await loader.actorIsAboveOrg(asActor(x1, org1), org2)).toBe(true);
      expect(await loader.actorIsAboveOrg(asActor(y, org1), org2)).toBe(true);
      expect(await loader.actorIsAboveOrg(asActor(root0, org0), org2)).toBe(
        true,
      );
      expect(await loader.actorIsAboveOrg(asActor(m, org0), org2)).toBe(true);
    });

    it('is false inside the organization, beside or below the marker, and for strangers', async () => {
      // y lives inside org1, not above it.
      expect(await loader.actorIsAboveOrg(asActor(y, org1), org1)).toBe(false);
      // The marker's own organization is not "above" itself.
      expect(await loader.actorIsAboveOrg(asActor(x1, org1), org1)).toBe(false);
      // In org0 but beside the marker.
      const beside = (
        await createPartner(testDb, org0, { recommenderId: root0 })
      ).accountId;
      expect(await loader.actorIsAboveOrg(asActor(beside, org0), org1)).toBe(
        false,
      );
      const stranger = await createOrgWithRoot(testDb);
      expect(
        await loader.actorIsAboveOrg(
          asActor(stranger.root.accountId, stranger.org),
          org2,
        ),
      ).toBe(false);
      // An organization founded by a link has nobody above it.
      expect(await loader.actorIsAboveOrg(asActor(root0, org0), org0)).toBe(
        false,
      );
      expect(await loader.actorIsAboveOrg(asActor(root0, null), org1)).toBe(
        false,
      );
    });
  });
});
